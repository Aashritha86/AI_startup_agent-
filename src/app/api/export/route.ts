import { NextRequest, NextResponse } from 'next/server';

export async function POST(request: NextRequest) {
  try {
    const body = await request.json();
    const { startup, format = 'json' } = body;

    if (!startup) {
      return NextResponse.json({ error: 'No startup data provided' }, { status: 400 });
    }

    if (format === 'markdown') {
      const d = startup.deliverables;
      const mdContent = `
# ${startup.title} - AI Startup Blueprint
> ${startup.tagline}

**Industry:** ${startup.industry}
**Target Audience:** ${startup.targetAudience}
**Description:** ${startup.description}

---

## 1. Business Model (Lean Canvas)
- **Problem:** ${d?.businessModel?.problem?.join(', ')}
- **Solution:** ${d?.businessModel?.solution?.join(', ')}
- **Value Proposition:** ${d?.businessModel?.valueProposition}
- **Unfair Advantage:** ${d?.businessModel?.unfairAdvantage}

## 2. Competitor Analysis
**Market Gap:** ${d?.competitorAnalysis?.marketGapSummary}
**Unfair Advantage:** ${d?.competitorAnalysis?.userUnfairAdvantage}

## 3. Tech Stack Architecture
- **Frontend:** ${d?.techStack?.frontend?.map((i: any) => `${i.tool} (${i.category})`).join(', ')}
- **Backend:** ${d?.techStack?.backend?.map((i: any) => `${i.tool}`).join(', ')}
- **Database:** ${d?.techStack?.database?.map((i: any) => `${i.tool}`).join(', ')}
- **Scalability Rating:** ${d?.techStack?.scalabilityRating}

## 4. Database Schema DDL
\`\`\`sql
${d?.databaseSchema?.sqlDDL}
\`\`\`

## 5. Cost Estimation (Year 1)
- **Year 1 Estimated Total:** $${d?.costEstimation?.year1TotalEstimated?.toLocaleString()}
- **Monthly Burn Rate:** $${d?.costEstimation?.monthlyBurnRate?.toLocaleString()}/mo

---
*Generated by AI Startup Builder*
`;
      return new NextResponse(mdContent, {
        headers: {
          'Content-Type': 'text/markdown',
          'Content-Disposition': `attachment; filename="${startup.title.toLowerCase().replace(/\s+/g, '-')}-blueprint.md"`,
        },
      });
    }

    return new NextResponse(JSON.stringify(startup, null, 2), {
      headers: {
        'Content-Type': 'application/json',
        'Content-Disposition': `attachment; filename="${startup.title.toLowerCase().replace(/\s+/g, '-')}-blueprint.json"`,
      },
    });
  } catch (error: any) {
    return NextResponse.json({ error: error.message }, { status: 500 });
  }
}
